SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS conversations (
    session_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    module TEXT,
    owner TEXT
);

CREATE TABLE IF NOT EXISTS messages (
    message_id INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    sources TEXT NOT NULL DEFAULT '[]',
    tools_used TEXT NOT NULL DEFAULT '[]',
    tables TEXT NOT NULL DEFAULT '[]',
    attachments TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL,
    FOREIGN KEY (session_id)
        REFERENCES conversations(session_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_messages_session
    ON messages(session_id, message_id);

CREATE INDEX IF NOT EXISTS idx_conversations_owner
    ON conversations(owner, updated_at);

-- Documents attached to a conversation. No foreign key: a document can be
-- uploaded before the first message creates the conversation.
CREATE TABLE IF NOT EXISTS attachments (
    attachment_id INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id TEXT NOT NULL,
    name TEXT NOT NULL,
    size_bytes INTEGER NOT NULL,
    pages INTEGER,
    chars INTEGER,
    text TEXT NOT NULL,
    truncated INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    owner TEXT,
    masked TEXT
);

CREATE INDEX IF NOT EXISTS idx_attachments_session
    ON attachments(session_id, attachment_id);

-- Knowledge base of the RAG: one row per document (the chunks and their
-- embeddings are in ChromaDB locally, in SAP HANA Cloud on SAP BTP)
CREATE TABLE IF NOT EXISTS kb_documents (
    name TEXT PRIMARY KEY,
    module TEXT,
    origin TEXT NOT NULL,
    size_bytes INTEGER NOT NULL,
    chars INTEGER NOT NULL,
    chunks INTEGER NOT NULL,
    content_hash TEXT NOT NULL,
    text TEXT NOT NULL,
    uploaded_by TEXT,
    created_at TEXT NOT NULL,
    masked TEXT
);
"""

