class SQLiteDatabase:

    dialect = "sqlite"
    label = "SQLite"

    def __init__(self, path=None):
        self.path = Path(path or SQLITE_PATH)

    @contextmanager
    def cursor(self):
        """Commit on success, roll back on error, always close."""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(self.path)
        connection.execute("PRAGMA foreign_keys = ON")
        try:
            yield Cursor(connection.cursor(), self.dialect)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()

    def initialize(self):
        with self.cursor() as cursor:
            # Columns first: the schema script creates indexes on columns old files do not have
            for table, column, definition in SQLITE_MIGRATIONS:
                existing = {row["name"] for row in cursor.execute(f"PRAGMA table_info({table})").fetchall()}
                if existing and column not in existing:
                    cursor.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")
            cursor._cursor.executescript(SQLITE_SCHEMA)
            # Conversations created before per-user history belong to the local user
            for table in ("conversations", "attachments"):
                cursor.execute(f"UPDATE {table} SET owner = ? WHERE owner IS NULL", (SQLITE_DEFAULT_OWNER,))
            # Documents stored before the "chars" column existed
            cursor.execute("UPDATE attachments SET chars = LENGTH(text) WHERE chars IS NULL")

    def describe(self):
        return {"backend": self.label, "location": str(self.path.name)}


class HanaDatabase:

    dialect = "hana"
    label = "SAP HANA Cloud"

    def __init__(self, credentials):
        self._credentials = credentials
        self._connection = None
        self._lock = threading.Lock()

    def _connect(self):
        from hdbcli import dbapi

        credentials = self._credentials
        try:
            connection = dbapi.connect(
                address=credentials["host"],
                port=int(credentials["port"]),
                user=credentials["user"],
                password=credentials["password"],
                currentSchema=credentials.get("schema"),
                encrypt=True,
                sslValidateCertificate=True,
                connectTimeout=10_000
            )
        except dbapi.Error as error:
            raise StoreUnavailable("The SAP HANA Cloud database of the chat history is not reachable.") from error
        connection.setautocommit(False)
        return connection

    @contextmanager
    def cursor(self):
        """One shared connection, used by one request at a time; reconnects after a network error."""
        from hdbcli import dbapi

        with self._lock:
            if self._connection is None or not self._connection.isconnected():
                self._connection = self._connect()
            connection = self._connection
            raw = connection.cursor()
            try:
                yield Cursor(raw, self.dialect)
                connection.commit()
            except Exception as error:
                try:
                    connection.rollback()
                except dbapi.Error:
                    pass
                # Connection lost: open a new one for the next request
                if isinstance(error, dbapi.Error) and not connection.isconnected():
                    self._connection = None
                    raise StoreUnavailable("The connection to SAP HANA Cloud was lost.") from error
                raise
            finally:
                try:
                    raw.close()
                except dbapi.Error:
                    pass

    def initialize(self):
        with self.cursor() as cursor:
            existing = {row["table_name"] for row in cursor.execute(
                "SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = CURRENT_SCHEMA"
            ).fetchall()}
            for name, ddl in HANA_TABLES.items():
                if name not in existing:
                    cursor.execute(ddl)
            columns = {(row["table_name"], row["column_name"]) for row in cursor.execute(
                "SELECT TABLE_NAME, COLUMN_NAME FROM SYS.TABLE_COLUMNS WHERE SCHEMA_NAME = CURRENT_SCHEMA"
            ).fetchall()}
            for table, column, ddl in HANA_MIGRATIONS:
                if (table, column) not in columns:
                    cursor.execute(ddl)
            indexes = {row["index_name"] for row in cursor.execute(
                "SELECT INDEX_NAME FROM SYS.INDEXES WHERE SCHEMA_NAME = CURRENT_SCHEMA"
            ).fetchall()}
            for name, ddl in HANA_INDEXES.items():
                if name not in indexes:
                    cursor.execute(ddl)

    def describe(self):
        return {"backend": self.label, "location": self._credentials.get("schema")}


_database = None
_database_lock = threading.Lock()


def get_database():
    global _database
    with _database_lock:
        if _database is None:
            credentials = hana_credentials()
            _database = HanaDatabase(credentials) if credentials else SQLiteDatabase()
        return _database


def set_database(database):
    """Replace the database (tests)."""
    global _database
    with _database_lock:
        _database = database
