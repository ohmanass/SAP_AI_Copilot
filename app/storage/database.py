"""
Database behind the chat history: SQLite locally, SAP HANA Cloud on SAP BTP.

SAP HANA Cloud is used as soon as a "hana" service (plan "schema") is bound to
the app (VCAP_SERVICES). Otherwise the history stays in a local SQLite file.
The SQL of app.storage.chat_store is shared by both engines; the differences
(table creation, identity columns, large text values) are handled here.

One HANA connection is kept open and shared (guarded by a lock); it is opened
again after a network error. When the database cannot be reached,
StoreUnavailable is raised so the API can answer without the history.
"""

import json
import os
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SQLITE_PATH = PROJECT_ROOT / "data" / "chat_history.db"


class StoreUnavailable(Exception):
    """The history database cannot be reached (message safe to show)."""


def hana_credentials():
    """Credentials of the bound SAP HANA schema, or None."""
    try:
        services = json.loads(os.getenv("VCAP_SERVICES", "{}"))
    except ValueError:
        return None
    instances = services.get("hana") or []
    return instances[0].get("credentials") if instances else None


