# ----------------------------------------------------------------------
# Cursor wrapper: same interface for both engines
# ----------------------------------------------------------------------

def _plain(value):
    # HANA returns large text (NCLOB) values as LOB objects
    return value.read() if hasattr(value, "read") else value


class Cursor:

    def __init__(self, cursor, dialect):
        self._cursor = cursor
        self.dialect = dialect

    def execute(self, sql, params=()):
        self._cursor.execute(sql, tuple(params))
        return self

    def executemany(self, sql, rows):
        self._cursor.executemany(sql, [tuple(row) for row in rows])
        return self

    def _columns(self):
        return [column[0].lower() for column in self._cursor.description]

    def fetchall(self):
        columns = self._columns()
        return [dict(zip(columns, map(_plain, row))) for row in self._cursor.fetchall()]

    def fetchone(self):
        row = self._cursor.fetchone()
        if row is None:
            return None
        return dict(zip(self._columns(), map(_plain, row)))

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def last_id(self):
        """Identity value generated by the last INSERT of this connection."""
        if self.dialect == "sqlite":
            return self._cursor.lastrowid
        self._cursor.execute("SELECT CURRENT_IDENTITY_VALUE() FROM DUMMY")
        return int(self._cursor.fetchone()[0])


